import { Bricolage_Grotesque, Instrument_Sans } from "next/font/google";
import "./globals.css";

const display = Bricolage_Grotesque({ subsets: ["latin"], variable: "--font-bricolage" });
const sans = Instrument_Sans({ subsets: ["latin"], variable: "--font-instrument" });

export const metadata = {
  title: "Your Name — AI visuals, websites and dashboards",
  description:
      "AI images and video, photo enhancement, landing pages, 3D for the web, copywriting, and spreadsheets or dashboards for small businesses.",
};

export default function RootLayout({ children }) {
    return (
        <html lang="en" className={`${display.variable} ${sans.variable}`} suppressHydrationWarning>
        <head>
            <script
                dangerouslySetInnerHTML={{
                    __html: `try{var t=localStorage.getItem('theme');if(t==='dark'||(!t&&matchMedia('(prefers-color-scheme: dark)').matches))document.documentElement.classList.add('dark')}catch(e){}`,
                }}
            />
        </head>
        <body className="antialiased">{children}</body>
        </html>
    );
}

